export function galleryBy(category: GalleryImage["category"]) {
  return gallery.filter((image) => image.category === category);
}

/** Look up a gallery image by its path (throws at build time if missing). */
export function img(src: string): GalleryImage {
  const found = gallery.find((image) => image.src === src);
  if (!found) throw new Error(`Image not in gallery: ${src}`);
  return found;
}
